// Regenerate the double-click entry after editing src/ with node game/pack-offline.mjs.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const directory = new URL('./src/', import.meta.url);
const sources = Object.fromEntries(readdirSync(directory).filter(path => path.endsWith('.js')).sort()
  .map(path => [path, readFileSync(new URL(path, directory), 'utf8')]));
const archive = gzipSync(JSON.stringify(sources), { level: 9 }).toString('base64');

async function startOffline(encoded) {
  // Chrome blocks external ES modules on file://. Blob URLs keep the original module graph.
  const bytes = Uint8Array.from(atob(encoded), char => char.charCodeAt(0));
  const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'));
  const sources = await new Response(stream).json();
  const urls = new Map();

  function moduleURL(name) {
    if (urls.has(name)) return urls.get(name);
    const code = sources[name].replace(/(\bfrom\s+['"])\.\/([^'"]+)(['"])/g,
      (match, prefix, dependency, suffix) => prefix + moduleURL(dependency) + suffix);
    const url = URL.createObjectURL(new Blob([code], { type: 'text/javascript' }));
    urls.set(name, url);
    return url;
  }

  try {
    await import(moduleURL('main.js'));
  } finally {
    for (const url of urls.values()) URL.revokeObjectURL(url);
  }
}

const script = `// Generated by pack-offline.mjs from src/.\n(${startOffline})(${JSON.stringify(archive)});\n`;
writeFileSync(new URL('./offline.min.js', import.meta.url), script);
